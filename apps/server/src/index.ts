import { createServer } from "node:http";
import { WebSocket, WebSocketServer, type RawData } from "ws";
import { isOpen, isSigilsSessionCode, sendJson, SessionManager, type PeerRole } from "./session-manager.js";

const PORT = Number(process.env.PORT ?? 3000);
const HOST = process.env.HOST ?? "0.0.0.0";
const IDLE_TIMEOUT_MS = positiveInt(process.env.IDLE_TIMEOUT_MS, 10 * 60 * 1000);
const OUTBOX_TIMEOUT_MS = positiveInt(process.env.OUTBOX_TIMEOUT_MS, 10 * 1000);
const MAX_PAYLOAD_BYTES = positiveInt(process.env.MAX_PAYLOAD_BYTES, 100 * 1024 * 1024);
const allowedOrigins = (process.env.ALLOWED_ORIGINS ?? "").split(",").map(v => v.trim()).filter(Boolean);

const httpServer = createServer((req, res) => {
  if (req.url === "/healthz") {
    res.writeHead(200, { "content-type": "application/json; charset=utf-8", "cache-control": "no-store" });
    res.end(JSON.stringify({ ok: true, service: "sigils-session-relay" }));
    return;
  }
  if (req.url === "/") {
    res.writeHead(200, { "content-type": "text/plain; charset=utf-8" });
    res.end("SIGILS Independent Session Relay\nWebSocket endpoint: /\nHealth: /healthz\n");
    return;
  }
  res.writeHead(404, { "content-type": "text/plain; charset=utf-8" });
  res.end("Not found");
});

const manager = new SessionManager({
  idleTimeoutMs: IDLE_TIMEOUT_MS,
  outboxTimeoutMs: OUTBOX_TIMEOUT_MS,
  onIdle: session => {
    const timeout = { type: "IdleTimeout", message: "10 minutes passed without any edits." };
    sendJson(session.computerCraft, timeout);
    sendJson(session.editor, timeout);
    closePeer(session.computerCraft, 4000, "Idle timeout");
    closePeer(session.editor, 4000, "Idle timeout");
    manager.remove(session);
  },
  onOutboxTimeout: (session, queued) => {
    for (const request of queued) {
      sendJson(session.editor, failResponse(
        String(request.type ?? "Unknown"),
        typeof request.reqId === "string" ? request.reqId : undefined,
        "PeerNotConnected",
        "Tried sending a message to ComputerCraft, but it did not reconnect within 10 seconds."
      ));
    }
    closePeer(session.editor, 4002, "ComputerCraft reconnect timeout");
  },
});

const wss = new WebSocketServer({
  server: httpServer,
  maxPayload: MAX_PAYLOAD_BYTES,
  perMessageDeflate: false,
  verifyClient: (info, done) => {
    const origin = info.origin;
    if (allowedOrigins.length > 0 && origin && !allowedOrigins.includes(origin)) {
      done(false, 403, "Origin not allowed");
      return;
    }
    done(true);
  },
});

wss.on("connection", socket => {
  let sessionId: string | undefined;
  let role: PeerRole | undefined;
  socket.on("error", error => console.error("[ws]", error.message));

  socket.on("message", (raw: RawData) => {
    const rawText = raw.toString();
    if (rawText === "ping") {
      if (isOpen(socket)) socket.send("pong");
      return;
    }

    let message: Record<string, unknown> & { type: string };
    try {
      const parsed: unknown = JSON.parse(rawText);
      if (!isRecord(parsed) || typeof parsed.type !== "string") {
        sendJson(socket, failResponse("Unknown", undefined, "UnknownError", "Message must be a JSON object with a string type."));
        return;
      }
      message = parsed as Record<string, unknown> & { type: string };
    } catch {
      sendJson(socket, failResponse("Unknown", undefined, "UnknownError", "Invalid JSON message."));
      return;
    }

    const currentSession = sessionId ? manager.sessions.get(sessionId) : undefined;
    if (currentSession) manager.touch(currentSession);

    try {
      if (message.type === "SessionCreate" && hasRequestId(message)) {
        if (role) return sendJson(socket, failResponse(message.type, message.reqId, "UnknownError", "This socket already has a role."));
        const id = message.sessionId;
        // v4.3 generates a four-character code on the CC side; preserve it verbatim.
        if (!isSigilsSessionCode(id)) {
          return sendJson(socket, failResponse(message.type, message.reqId, "UnknownError", "Session ID must be the four-uppercase-letter code generated by SIGILS."));
        }
        const session = manager.create(id, socket);
        if (!session) return sendJson(socket, failResponse(message.type, message.reqId, "SessionIdTaken", "Session ID already exists"));
        sessionId = id;
        role = "CC";
        sendJson(socket, {
          type: "ConfirmationResponse", respondingTo: "SessionCreate", ok: true,
          reqId: message.reqId, ccReconnectToken: session.ccReconnectToken,
        });
        return;
      }

      if (message.type === "SessionJoin" && hasRequestId(message)) {
        if (role) return sendJson(socket, failResponse(message.type, message.reqId, "UnknownError", "This socket already has a role."));
        if (typeof message.sessionId !== "string") return sendJson(socket, failResponse(message.type, message.reqId, "SessionIdNotExist", "Session ID does not exist"));
        const session = manager.join(message.sessionId, socket);
        if (!session) {
          const exists = manager.sessions.has(message.sessionId);
          return sendJson(socket, failResponse(message.type, message.reqId, exists ? "SessionHasEditor" : "SessionIdNotExist", exists ? "Someone is already editing the factory" : "Session ID does not exist"));
        }
        sessionId = message.sessionId;
        role = "editor";
        sendJson(socket, successResponse("SessionJoin", message.reqId));
        return;
      }

      if (message.type === "SessionRejoin" && hasRequestId(message)) {
        if (role) return sendJson(socket, failResponse(message.type, message.reqId, "UnknownError", "This socket already has a role."));
        if (typeof message.sessionId !== "string" || typeof message.ccReconnectToken !== "string") {
          return sendJson(socket, failResponse(message.type, message.reqId, "SessionIdNotExist", "Cannot reconnect without a valid session ID and token"));
        }
        const session = manager.rejoin(message.sessionId, message.ccReconnectToken, socket);
        if (!session) {
          const exists = manager.sessions.has(message.sessionId);
          return sendJson(socket, failResponse(message.type, message.reqId, exists ? "BadReconnectToken" : "SessionIdNotExist", exists ? "Reconnect token incorrect" : "Cannot connect to an expired session ID"));
        }
        sessionId = message.sessionId;
        role = "CC";
        sendJson(socket, {
          type: "ConfirmationResponse", respondingTo: "SessionRejoin", ok: true,
          reqId: message.reqId, ccReconnectToken: session.ccReconnectToken,
        });
        // The CC client waits synchronously for this confirmation before it can
        // safely process queued editor traffic. Send the confirmation first.
        manager.flushOutbox(session);
        return;
      }

      const session = sessionId ? manager.sessions.get(sessionId) : undefined;
      if (!session || !role) {
        if (hasRequestId(message)) sendJson(socket, failResponse(message.type, message.reqId, "SessionIdNotExist", "Join or create a session before sending messages."));
        return;
      }

      if (message.type === "SessionClose" && hasRequestId(message) && role === "CC") {
        sendJson(session.editor, { type: "SessionClose", reqId: message.reqId });
        closePeer(session.editor, 4003, "Session closed by CC");
        manager.remove(session);
        return;
      }

      if (message.type === "CcUpdatedFactory" && role === "CC") {
        if (!isOpen(session.editor)) {
          sendJson(socket, failResponse(message.type, undefined, "PeerNotConnected", "Tried sending a message to the editor, but it isn't connected on this session."));
        } else {
          sendJson(session.editor, message);
        }
        return;
      }

      if (role === "editor") {
        if (!isOpen(session.computerCraft)) {
          if (hasRequestId(message)) manager.queueForComputer(session, message);
          else sendJson(socket, failResponse(message.type, undefined, "PeerNotConnected", "ComputerCraft is not connected."));
        } else {
          sendJson(session.computerCraft, message);
        }
      } else if (role === "CC") {
        if (!isOpen(session.editor)) {
          if (hasRequestId(message)) sendJson(socket, failResponse(message.type, message.reqId, "PeerNotConnected", "The editor is not connected on this session."));
        } else {
          sendJson(session.editor, message);
        }
      }
    } catch (error) {
      console.error("[relay] message handling failed:", error);
      if (hasRequestId(message)) sendJson(socket, failResponse(message.type, message.reqId, "UnknownError", "Session relay encountered an internal error."));
    }
  });

  socket.on("close", () => {
    if (!sessionId || !role) return;
    const session = manager.sessions.get(sessionId);
    if (!session) return;
    // A replaced CC socket must not detach the newly reconnected socket.
    if (role === "CC" && session.computerCraft === socket) delete session.computerCraft;
    if (role === "editor" && session.editor === socket) delete session.editor;
  });
});

httpServer.listen(PORT, HOST, () => console.log(`[sigils-relay] listening on ${HOST}:${PORT}`));

function positiveInt(raw: string | undefined, fallback: number): number {
  const parsed = Number(raw);
  return Number.isSafeInteger(parsed) && parsed > 0 ? parsed : fallback;
}
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function hasRequestId(value: Record<string, unknown>): value is Record<string, unknown> & { reqId: string } {
  return typeof value.reqId === "string" && value.reqId.length > 0;
}
function successResponse(respondingTo: string, reqId: string) {
  return { type: "ConfirmationResponse", respondingTo, reqId, ok: true };
}
function failResponse(respondingTo: string, reqId: string | undefined, error: string, message: string) {
  return { type: "ConfirmationResponse", respondingTo, ...(reqId ? { reqId } : {}), ok: false, error, message };
}
function closePeer(socket: WebSocket | undefined, code: number, reason: string) {
  if (isOpen(socket)) socket.close(code, reason);
}
